const shirt = fileURLToPath(new URL('../../samples/black shirt test.JPG', import.meta.url))
const pants = fileURLToPath(new URL('../../samples/blue pants test.JPG', import.meta.url))

const template = (page: Page, kind = 'Shirt') => page.getByRole('img', { name: `${kind} template canvas` })
const tools = (page: Page) => page.getByRole('complementary', { name: 'Studio tools' })
const stack = (page: Page) => page.locator('.studio-layers')
const status = (page: Page) => page.locator('.studio-status')

function pixel(canvas: Locator, x: number, y: number) {
  return canvas.evaluate((node: HTMLCanvasElement, p) =>
    [...node.getContext('2d')!.getImageData(p.x, p.y, 1, 1).data], { x, y })
}

async function gesture(page: Page, canvas: Locator, start: [number, number], end = start) {
  await canvas.scrollIntoViewIfNeeded()
  const bounds = (await canvas.boundingBox())!
  const [w, h] = await canvas.evaluate((node: HTMLCanvasElement) => [node.width, node.height])
  const move = ([x, y]: [number, number]) => page.mouse.move(bounds.x + x * bounds.width / w, bounds.y + y * bounds.height / h)
  await move(start)
  await page.mouse.down()
  await move(end)
  await page.mouse.up()
}

test('paints within a face and saves editable layers, masks and snapshots across reloads', async ({ page }) => {
  await page.goto('/#studio')
  const canvas = template(page)
  await expect(canvas).toBeVisible()
  await page.getByRole('textbox', { name: 'Project name' }).fill('Blue prototype')
  await page.getByRole('button', { name: 'Add layer' }).click()
  await tools(page).getByRole('button', { name: 'Brush', exact: true }).click()
  await page.getByRole('slider', { name: 'Size', exact: true }).fill('38')
  await gesture(page, canvas, [234, 114], [272, 114])
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([59, 130, 246, 255])
  await expect.poll(() => pixel(canvas, 226, 114)).toEqual([0, 0, 0, 0])
  await page.locator('.studio-viewport').press('Control+z')
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([0, 0, 0, 0])
  await page.locator('.studio-viewport').press('Control+Shift+z')
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([59, 130, 246, 255])

  await page.getByRole('button', { name: 'Add group' }).click()
  await page.getByRole('button', { name: 'Hide group Group 1' }).click()
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([0, 0, 0, 0])
  await page.getByRole('button', { name: 'Show group Group 1' }).click()
  await page.getByText('Named snapshots', { exact: true }).click()
  await page.getByRole('textbox', { name: 'Snapshot name' }).fill('Before mask')
  await page.getByRole('button', { name: 'Save snapshot' }).click()
  await page.getByRole('checkbox', { name: 'Edit layer mask' }).check()
  await gesture(page, canvas, [255, 114])
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([0, 0, 0, 0])
  await expect(page.getByRole('button', { name: 'Remove mask' })).toBeVisible()
  await expect(status(page)).toHaveText('Saved')

  await page.goto('/#projects')
  await page.getByRole('searchbox', { name: 'Search' }).fill('prototype')
  const saved = page.getByRole('button', { name: /Blue prototype Shirt/ })
  await expect(saved).toBeVisible()
  const folder = page.getByRole('combobox', { name: 'Folder for Blue prototype' })
  await folder.fill('Test designs')
  await folder.press('Enter')
  await page.getByRole('combobox', { name: 'Folder', exact: true }).selectOption({ label: 'Test designs' })
  await page.getByRole('button', { name: 'Duplicate Blue prototype', exact: true }).click()
  await page.getByRole('button', { name: 'Delete Blue prototype copy', exact: true }).click()
  await page.getByRole('button', { name: 'Delete project', exact: true }).click()
  await expect(page.getByRole('button', { name: /Blue prototype copy Shirt/ })).toHaveCount(0)
  await saved.click()
  await expect(stack(page).locator('.studio-layer')).toHaveCount(1)
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([0, 0, 0, 0])
  await page.getByText('Named snapshots', { exact: true }).click()
  await page.getByRole('button', { name: 'Restore Before mask' }).click()
  await expect.poll(() => pixel(canvas, 255, 114)).toEqual([59, 130, 246, 255])
})

test('cuts a real photo, drags a piece into a face and wraps a limb without spilling into template gutters', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto('/#studio')
  const canvas = template(page)
  await page.getByLabel('Import photos', { exact: true }).setInputFiles(shirt)
  await expect(page.getByRole('checkbox', { name: 'Show cutout' })).toBeChecked({ timeout: 15_000 })
  const photo = page.getByRole('img', { name: 'Photo to cut' })
  const bounds = (await photo.boundingBox())!
  await photo.click({ position: { x: bounds.width * .48, y: bounds.height * .56 } })
  await page.getByRole('button', { name: 'Cut selected piece' }).click()
  const piece = page.getByRole('button', { name: 'black shirt test piece 1', exact: true })
  const target = (await canvas.boundingBox())!
  await piece.dragTo(canvas, { targetPosition: { x: 292 * target.width / 585, y: 145 * target.height / 559 } })
  await expect(stack(page).locator('.studio-layer')).toHaveCount(1)
  await expect.poll(async () => (await pixel(canvas, 292, 141))[3]).toBe(255)

  const panels = page.getByRole('complementary', { name: 'Studio panels' })
  await panels.getByRole('button', { name: 'Regions', exact: true }).click()
  await panels.getByRole('button', { name: 'Right arm front', exact: true }).click()
  await panels.getByRole('button', { name: 'Wrap around limb' }).click()
  await panels.getByRole('checkbox', { name: 'Show seams' }).check()
  await expect(panels.getByRole('img', { name: 'Fabric across adjacent side seams' })).toBeVisible()
  await expect.poll(async () => (await pixel(canvas, 240, 425))[3]).toBe(255)
  await expect.poll(async () => (await pixel(canvas, 106, 425))[3]).toBe(255)
  expect(await pixel(canvas, 215, 425)).toEqual([0, 0, 0, 0])

  await page.getByRole('button', { name: 'Avatar preview', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Flat front mannequin preview' })).toBeVisible()
  const exported = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download PNG', exact: true }).click()
  const bytes = await readFile(await (await exported).path())
  expect([bytes.readUInt32BE(16), bytes.readUInt32BE(20)]).toEqual([585, 559])
  await expect(page.getByRole('heading', { name: 'Catalog checklist' })).toBeVisible()
})

test('hands off an edited Auto Bash result as independent layers and keeps its source photo', async ({ page }) => {
  await page.goto('/#auto-bash')
  await page.locator('.drop-zone input[type=file]').setInputFiles(pants)
  await page.getByRole('button', { name: 'Make my Roblox clothing' }).click()
  const edit = page.getByRole('button', { name: 'Edit in Studio' })
  await expect(edit).toBeEnabled({ timeout: 20_000 })
  await page.getByRole('slider', { name: 'Brightness' }).fill('20')
  await expect(edit).toBeEnabled()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download PNG', exact: true }).click()
  const bytes = await readFile(await (await download).path())
  const expected = await page.evaluate(async (data) => {
    const bitmap = await createImageBitmap(new Blob([new Uint8Array(data)], { type: 'image/png' }))
    const ctx = new OffscreenCanvas(585, 559).getContext('2d')!
    ctx.drawImage(bitmap, 0, 0)
    bitmap.close()
    return Array.from(ctx.getImageData(295, 147, 1, 1).data)
  }, Array.from(bytes))

  await edit.click()
  const canvas = template(page, 'Pants')
  await expect(page.getByRole('heading', { name: 'Studio', exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Project name' })).toHaveValue('Auto Bash Pants')
  await expect(stack(page).locator('.studio-layer')).toHaveCount(18)
  await expect(page.getByRole('button', { name: /blue pants test.JPG/i })).toBeVisible()
  await expect.poll(() => pixel(canvas, 295, 147)).toEqual(expected)
  await stack(page).getByRole('button', { name: 'Hide Waist front', exact: true }).click()
  await expect.poll(() => pixel(canvas, 295, 147)).toEqual([0, 0, 0, 0])
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect.poll(() => pixel(canvas, 295, 147)).toEqual(expected)
})

test('imports a template PNG and moves or masks its pixels without changing neighboring faces', async ({ page }) => {
  await page.goto('/#studio')
  const sample = fileURLToPath(new URL('../../samples/out/black-shirt-test.png', import.meta.url))
  await page.getByLabel('Import template PNG', { exact: true }).setInputFiles(sample)
  await expect(page.getByRole('textbox', { name: 'Project name' })).toHaveValue('black-shirt-test')
  const canvas = template(page)
  await expect.poll(async () => (await pixel(canvas, 292, 146))[3]).toBe(255)
  const neighbor = await pixel(canvas, 440, 140)
  await stack(page).getByRole('button', { name: 'Torso front', exact: true }).click()
  await tools(page).getByRole('button', { name: 'Perspective', exact: true }).click()
  await expect(page.locator('.studio-control-point')).toHaveCount(4)
  await gesture(page, canvas, [231, 75], [248, 87])
  await expect.poll(async () => (await pixel(canvas, 234, 78))[3]).toBe(0)
  expect(await pixel(canvas, 440, 140)).toEqual(neighbor)
  await tools(page).getByRole('button', { name: 'Mesh Warp', exact: true }).click()
  await expect(page.locator('.studio-control-point')).toHaveCount(9)
  await page.getByRole('button', { name: 'Reset warp' }).click()
  await expect.poll(async () => (await pixel(canvas, 234, 78))[3]).toBe(255)
  expect(await pixel(canvas, 440, 140)).toEqual(neighbor)
})
